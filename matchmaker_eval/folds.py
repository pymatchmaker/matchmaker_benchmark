"""Evaluation folds for the matchmaker benchmark.

A *fold* is a frozen CSV under ``data/folds/`` that lists exactly which
(score, performance, ground-truth) triples a benchmark run touches. Freezing
the list in the repository is what makes two submissions comparable: the
leaderboard number only means something if every entry saw the same pieces.

Three folds ship with the repository:

``example``
    A single piece that lives in ``resources/`` inside this repository. No
    download needed, so CI can smoke-test a submission in a couple of minutes.
``tuning``
    The development fold. Tune, sweep and overfit here as much as you like.
``eval``
    The leaderboard fold. Must not be used for tuning — see
    ``docs/eval-protocol.md``.

Fold CSVs are generated by ``matchmaker_eval/make_folds.py`` and committed, so
a change to the benchmark's contents always shows up as a reviewable diff.

Audio and MIDI performances live outside the repository (they are far too
large to version). Point the runner at them with::

    export MATCHMAKER_DATA_DIR=~/data     # default

and see ``matchmaker_eval/download_data.py`` for fetching them.
"""

import csv
import os
from dataclasses import dataclass
from pathlib import Path
from typing import Iterator, List, Optional, Union

REPO_ROOT = Path(__file__).resolve().parent.parent
FOLD_DIR = REPO_ROOT / "data" / "folds"

#: Root under which the (undistributed) datasets are expected.
DATA_ROOT = Path(os.environ.get("MATCHMAKER_DATA_DIR", "~/data")).expanduser()

#: Directory names the original upstream datasets unpack into. The benchmark
#: data repository instead uses the dataset name itself, so a local copy in
#: either shape works: the repository layout wins when it is present.
LEGACY_DIRS = {
    "asap": "asap-dataset-matchmaker",
    "batik": "batik_plays_mozart",
    "vienna": "vienna4x22",
}

#: The subdirectories a fold CSV addresses inside a dataset root. A directory
#: without any of them is not laid out the way the folds expect, whatever it is
#: called.
LAYOUT_DIRS = ("score", "midi", "match", "audio")


def has_expected_layout(path: Path) -> bool:
    """Is this directory shaped the way the fold CSVs address files?

    An upstream dataset unpacks into its *own* structure — ASAP nests by
    composer, Batik keeps `scores_effective/` — which is not the flat
    `score/ midi/ match/ audio/` the folds name. Sharing only a directory name
    with such a copy is not enough to use it.
    """
    return path.is_dir() and any((path / name).is_dir() for name in LAYOUT_DIRS)


def dataset_root(dataset: str) -> Path:
    """Where this dataset's files live under ``MATCHMAKER_DATA_DIR``.

    ``<data root>/<dataset>`` mirrors the data repository and is what
    ``fetch_data.py`` writes into, so it is preferred and is also the answer
    when nothing is on disk yet — the download then lands in the right place.

    A copy under the upstream directory name is used instead only when it is
    actually laid out the way the folds expect. Returning one that merely has
    the right name sends every path into a differently-shaped tree: the run
    fails with paths the user never configured, and any fetch fills that tree
    with a second, repo-shaped copy alongside the original.
    """
    if dataset == "local":
        return REPO_ROOT
    repo_style = DATA_ROOT / dataset
    if repo_style.is_dir():
        return repo_style
    legacy = DATA_ROOT / LEGACY_DIRS.get(dataset, dataset)
    if legacy != repo_style and has_expected_layout(legacy):
        return legacy
    return repo_style


#: Kept for callers that want the mapping eagerly; prefer ``dataset_root()``.
DATASET_ROOTS = {
    name: dataset_root(name) for name in (*LEGACY_DIRS, "local")
}

FOLD_COLUMNS = [
    "piece_id",
    "dataset",
    "composer",
    "title",
    "xml_score",
    "midi_performance",
    "audio_performance",
    "match",
    "difficulty",
]

#: Datasets whose beat annotations are in musical (notated) beats.
MUSICAL_BEAT_DATASETS = {"asap"}

#: The fold the leaderboard publishes. Runs on any other fold are development
#: output and are kept somewhere else, so they can never overwrite a published
#: record.
LEADERBOARD_FOLD = "eval"

#: Audio may arrive in a different container than the fold CSV names: the
#: original datasets ship wav, the benchmark data repository ships mp3. A piece
#: is satisfied by any of these, tried in order.
AUDIO_EXTENSIONS = (".wav", ".mp3", ".flac", ".ogg")


class FoldError(Exception):
    """Raised when a fold cannot be loaded or its files are missing."""


@dataclass(frozen=True)
class Piece:
    """One (score, performance, ground truth) triple of a fold."""

    piece_id: str
    dataset: str
    composer: str
    title: str
    xml_score: str
    midi_performance: str
    audio_performance: str
    match: str
    difficulty: str = ""

    @property
    def root(self) -> Path:
        if self.dataset not in DATASET_ROOTS:
            raise FoldError(
                f"Unknown dataset '{self.dataset}' for piece '{self.piece_id}'. "
                f"Known: {sorted(DATASET_ROOTS)}"
            )
        # Resolved per access, so a directory appearing after import is seen.
        return dataset_root(self.dataset)

    @property
    def score_path(self) -> Path:
        return self.root / self.xml_score

    @property
    def match_path(self) -> Path:
        return self.root / self.match

    @property
    def musical_beat(self) -> bool:
        return self.dataset in MUSICAL_BEAT_DATASETS

    def performance_path(self, input_type: str) -> Path:
        """Resolve the performance file, accepting any known audio container.

        Returns the canonical path when nothing is on disk yet, so error
        messages and download targets name the file the fold asked for.
        """
        rel = self.midi_performance if input_type == "midi" else self.audio_performance
        if not rel:
            raise FoldError(f"Piece '{self.piece_id}' has no {input_type} performance.")
        canonical = self.root / rel
        if input_type == "midi" or canonical.exists():
            return canonical
        for extension in AUDIO_EXTENSIONS:
            candidate = canonical.with_suffix(extension)
            if candidate.exists():
                return candidate
        return canonical

    def oracle_tempo(self, input_type: str) -> Optional[float]:
        """The performance's estimated tempo in BPM, or None if not published.

        Only followers that declare they use it are given it — see
        ``docs/eval-protocol.md``. The value lives in the data repository's
        metadata CSV, keyed by the same paths the fold names.
        """
        table = _tempo_table(self.dataset)
        if not table:
            return None
        relative = (
            self.midi_performance if input_type == "midi" else self.audio_performance
        )
        for key in (f"{self.dataset}/{relative}", relative):
            if key in table:
                return table[key]
        # The metadata may name a different container for the same recording.
        stem = Path(relative).stem if relative else None
        if stem:
            for key, tempo in table.items():
                if Path(key).stem == stem:
                    return tempo
        return None

    def audio_candidates(self) -> List[Path]:
        """Every container this piece's audio could be distributed in."""
        if not self.audio_performance:
            return []
        canonical = self.root / self.audio_performance
        seen, candidates = set(), []
        for extension in AUDIO_EXTENSIONS:
            candidate = canonical.with_suffix(extension)
            if candidate not in seen:
                seen.add(candidate)
                candidates.append(candidate)
        return candidates

    def has_performance(self, input_type: str) -> bool:
        return bool(
            self.midi_performance if input_type == "midi" else self.audio_performance
        )

    def required_files(self, input_type: str) -> List[Path]:
        return [self.score_path, self.performance_path(input_type), self.match_path]


def fold_path(fold: Union[str, Path]) -> Path:
    """Resolve a fold name (``"eval"``) or an explicit path to a CSV."""
    candidate = Path(fold)
    if candidate.suffix == ".csv" and candidate.exists():
        return candidate
    named = FOLD_DIR / f"{fold}.csv"
    if named.exists():
        return named
    available = sorted(p.stem for p in FOLD_DIR.glob("*.csv"))
    raise FoldError(f"Unknown fold '{fold}'. Available: {available}")


def load_fold(fold: Union[str, Path], input_type: Optional[str] = None) -> List[Piece]:
    """Load a fold, optionally keeping only pieces usable for ``input_type``."""
    path = fold_path(fold)
    with open(path, newline="") as f:
        rows = list(csv.DictReader(f))
    if not rows:
        raise FoldError(f"Fold '{path}' is empty.")
    missing_cols = set(FOLD_COLUMNS) - set(rows[0])
    if missing_cols:
        raise FoldError(f"Fold '{path}' is missing columns: {sorted(missing_cols)}")

    pieces = [
        Piece(**{c: (row.get(c) or "").strip() for c in FOLD_COLUMNS}) for row in rows
    ]
    if input_type is not None:
        pieces = [p for p in pieces if p.has_performance(input_type)]
        if not pieces:
            raise FoldError(f"Fold '{path}' has no {input_type} performances.")
    return pieces


def write_fold(pieces: Iterator[Piece], path: Path) -> int:
    """Write pieces to a fold CSV. Returns the number of rows written."""
    path.parent.mkdir(parents=True, exist_ok=True)
    n = 0
    with open(path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=FOLD_COLUMNS)
        writer.writeheader()
        for piece in pieces:
            writer.writerow({c: getattr(piece, c) for c in FOLD_COLUMNS})
            n += 1
    return n


def shard_of(pieces: List[Piece], shard: int, num_shards: int) -> List[Piece]:
    """Take one shard of a fold.

    Round-robin rather than contiguous blocks, so every shard gets a similar
    mix of datasets and piece lengths and the parallel jobs finish at roughly
    the same time. Membership depends only on the fold file and the shard
    count, so two runs with the same settings split identically.
    """
    if num_shards < 1:
        raise FoldError(f"num_shards must be at least 1, got {num_shards}.")
    if not 0 <= shard < num_shards:
        raise FoldError(f"shard must be in [0, {num_shards}), got {shard}.")
    return pieces[shard::num_shards]


#: Column of the data repository's metadata CSV holding the oracle tempo.
#: Overridable in data/data_sources.yaml as ``oracle_tempo_column``.
ORACLE_TEMPO_COLUMN = "estimated_bpm"

#: dataset -> {file path as the metadata names it: tempo}, filled on first use.
_TEMPO_CACHE: dict = {}


class OracleTempoUnavailable(FoldError):
    """Raised when a run asks for the oracle tempo and it is not there.

    Deliberately fatal rather than a warning: a follower given the tempo and a
    follower denied it are two different measurements, and a row that quietly
    became the second while still being labelled the first is worse than a
    failed run.
    """


def _tempo_column() -> str:
    """The metadata column holding the tempo, from the data source config."""
    try:
        import yaml

        config = yaml.safe_load(
            (REPO_ROOT / "data" / "data_sources.yaml").read_text()
        ) or {}
    except Exception:
        return ORACLE_TEMPO_COLUMN
    return str(config.get("oracle_tempo_column") or ORACLE_TEMPO_COLUMN)


def _tempo_table(dataset: str) -> dict:
    """``{path: tempo}`` for one dataset, read from its metadata CSV.

    The metadata CSV is the data repository describing itself: it names every
    file it holds, so the tempo travels with the data rather than being a
    second table this repository has to keep in step.
    """
    if dataset in _TEMPO_CACHE:
        return _TEMPO_CACHE[dataset]

    column = _tempo_column()
    table: dict = {}
    root = dataset_root(dataset)
    candidates = sorted(root.glob(f"metadata-{dataset}*.csv"))
    for path in candidates:
        with open(path, newline="") as handle:
            reader = csv.DictReader(handle)
            if reader.fieldnames is None or column not in reader.fieldnames:
                continue
            for row in reader:
                raw = (row.get(column) or "").strip()
                if not raw:
                    continue
                try:
                    tempo = float(raw)
                except ValueError:
                    continue
                for field in ("midi", "audio", "score", "match"):
                    key = (row.get(field) or "").strip()
                    if key:
                        table[key] = tempo
    _TEMPO_CACHE[dataset] = table
    return table


def clear_tempo_cache() -> None:
    """Forget the parsed metadata. For tests, and after a fresh download."""
    _TEMPO_CACHE.clear()


def missing_files(pieces: List[Piece], input_type: str) -> List[Path]:
    """Return every required file that is not on disk (deduplicated, ordered)."""
    missing, seen = [], set()
    for piece in pieces:
        for path in piece.required_files(input_type):
            if path not in seen and not path.exists():
                seen.add(path)
                missing.append(path)
    return missing


def require_files(pieces: List[Piece], input_type: str) -> None:
    """Fail early — before a multi-hour run — if data is not downloaded."""
    missing = missing_files(pieces, input_type)
    if missing:
        shown = "\n  ".join(str(p) for p in missing[:10])
        more = f"\n  ... and {len(missing) - 10} more" if len(missing) > 10 else ""
        raise FoldError(
            f"{len(missing)} required file(s) not found:\n  {shown}{more}\n\n"
            f"Datasets are expected under {DATA_ROOT} (override with "
            "MATCHMAKER_DATA_DIR). They are normally downloaded automatically "
            "from the data repository named in data/data_sources.yaml, so "
            "reaching this message means the download was switched off "
            "(--no-fetch), or could not run.\n\n"
            "Fetch them:\n"
            f"  python matchmaker_eval/fetch_data.py --fold <fold> "
            f"--input-type {input_type}\n\n"
            "Check the source is reachable:\n"
            "  python matchmaker_eval/fetch_data.py --probe "
            f"--fold <fold> --input-type {input_type}"
        )
